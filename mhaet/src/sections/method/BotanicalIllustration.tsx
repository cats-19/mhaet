function drawStyle(draw: boolean, delay: number, dur: number): CSSProperties {
  return {
    strokeDasharray: 1,
    strokeDashoffset: draw ? 0 : 1,
    transition: `stroke-dashoffset ${dur}s cubic-bezier(0.4, 0, 0.2, 1) ${delay}s`,
  };
}

function fillStyle(draw: boolean, delay: number, to = 0.95, dur = 1): CSSProperties {
  return {
    opacity: draw ? to : 0,
    transition: `opacity ${dur}s ease ${delay}s`,
  };
}

/** Native viewBox is 0 0 280 420. We center it in the row's 400×400 frame. */
const SX = 1.05;
const SY = 0.95;
const TX = 28;
const TY = 0;

export function BotanicalArt({ uid, draw }: { uid: string; draw: boolean }) {
  const line = `line-${uid}`;
  const soft = `soft-${uid}`;
  const cream = `cream-${uid}`;

  return (
    <g transform={`translate(${TX} ${TY}) scale(${SX} ${SY})`}>
      {/* Stems draw on first, so the branch forms before the leaves appear. */}
      <g fill="none" stroke={`url(#${line})`} strokeLinecap="round" strokeLinejoin="round">
        {stems.map((s, i) => (
          <path
            key={`stem-${i}`}
            d={s.d}
            strokeWidth={s.w}
            pathLength={1}
            style={drawStyle(draw, 0.2 + i * 0.12, 1.4)}
          />
        ))}
      </g>

      {/* Short, folded leaves at the top of the branch. */}
      <g fill={`url(#${line})`}>
        {topLeaves.map((d, i) => (
          <path key={`top-${i}`} d={d} style={fillStyle(draw, 0.9 + i * 0.05)} />
        ))}
      </g>

      {/* Long curling blades in the lower, ribbon-like part. */}
      <g fill={`url(#${line})`}>
        {blades.map((d, i) => (
          <path key={`blade-${i}`} d={d} style={fillStyle(draw, 1.2 + i * 0.05)} />
        ))}
      </g>

      {/* Loose outline of overlapping petals on the right. */}
      <g fill={`url(#${line})`}>
        {flower.map((d, i) => (
          <path key={`flower-${i}`} d={d} style={fillStyle(draw, 1.6 + i * 0.06)} />
        ))}
      </g>

      {/* Small, lighter accents at the base. */}
      <g fill={`url(#${soft})`}>
        {accents.map((d, i) => (
          <path key={`accent-${i}`} d={d} style={fillStyle(draw, 2.0 + i * 0.1, 0.7)} />
        ))}
      </g>

      {/* Cream veins trace across the leaves, like the light cuts in the study. */}
      <g fill="none" stroke={`url(#${cream})`} strokeLinecap="round" strokeLinejoin="round">
        {veins.map((v, i) => (
          <path
            key={`vein-${i}`}
            d={v.d}
            strokeWidth={v.w}
            pathLength={1}
            style={drawStyle(draw, 2.0 + (i % 6) * 0.14, 0.9)}
          />
        ))}
      </g>
    </g>
  );
}
